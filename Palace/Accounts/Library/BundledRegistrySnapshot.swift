import Foundation
import PalaceLogging

/// Abstraction over bundle resource lookup. Production code uses `Bundle.main`;
/// tests inject a stub that resolves resources from arbitrary on-disk paths.
protocol BundleResourceResolving {
    func resourceURL(forName name: String, extension ext: String) -> URL?
}

extension Bundle: BundleResourceResolving {
    func resourceURL(forName name: String, extension ext: String) -> URL? {
        url(forResource: name, withExtension: ext)
    }
}

/// Loads the build-time snapshot of the library registry that ships inside
/// the app bundle (PP-4258).
///
/// On cold first launch — when no on-disk catalog cache exists — the app
/// loads this snapshot so the library picker appears immediately, then
/// kicks off an asynchronous incremental refresh (PP-4259) to pick up
/// anything that changed since the snapshot was cut at build time.
///
/// The snapshot is generated by `scripts/snapshot-library-registry.py`
/// against `https://registry.palaceproject.io/libraries/crawlable` and
/// is checked into `Palace/Accounts/Library/bundled_registry.json`.
enum BundledRegistrySnapshot {

    /// Resource basename (without extension) used to locate the snapshot
    /// inside the app bundle.
    static let resourceName = "bundled_registry"
    static let resourceExtension = "json"

    /// Loads the bundled snapshot bytes, or returns `nil` if the resource
    /// is missing or unreadable. The returned `Data` is the raw OPDS 2.0
    /// catalogs feed, ready to be parsed by `OPDS2CatalogsFeed.fromData`.
    ///
    /// Returns `nil` (rather than throwing) so callers can fall through
    /// to the network fetch without special-casing — a missing snapshot
    /// is a degraded but recoverable startup, not an error condition.
    static func load(resolver: BundleResourceResolving = Bundle.main) -> Data? {
        guard let url = resolver.resourceURL(forName: resourceName, extension: resourceExtension) else {
            Log.debug(#file, "Bundled registry snapshot is not present in this bundle")
            return nil
        }
        do {
            return try Data(contentsOf: url)
        } catch {
            Log.error(#file, "Failed to read bundled registry snapshot at \(url.lastPathComponent): \(error.localizedDescription)")
            return nil
        }
    }
}
